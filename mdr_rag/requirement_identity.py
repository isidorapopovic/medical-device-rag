"""Deterministic legal anchors, independent of model-written paraphrases.

Positions are in normalized extracted text, not verified raw quotation offsets.
These anchors are register identities; raw-span evidence belongs to Stage 2.
"""
from .core import norm
from .report_state import fingerprint


def anchor_key(requirement: dict) -> tuple:
    return (requirement["legal_source"], requirement["legal_sha256"],
            requirement["legal_page"], requirement["legal_source_chunk_id"],
            norm(requirement["exact_quote"]), norm(requirement["provision"]))


def assign_identity(requirement: dict, text: str, previous: list[dict]) -> dict:
    record = dict(requirement)
    quote = norm(record["exact_quote"])
    position = norm(text).find(quote)
    if position < 0:
        raise ValueError("Cannot derive identity from an unverifiable legal anchor")
    # Existing extractor keeps only one obligation per quote. Distinct obligations
    # with identical anchors need an explicit obligation_position to distinguish them.
    ordinal = record.get("obligation_position", 1)
    record["identity_anchor"] = {"normalized_quote_position": position,
                                 "obligation_position": ordinal,
                                 "scheme": "legal-anchor-v1"}
    matches = [old for old in previous if anchor_key(old) == anchor_key(record)
               and old.get("obligation_position", 1) == ordinal]
    if len(matches) > 1:
        raise ValueError("Ambiguous previous requirement anchor; resolve duplicate obligations before extracting")
    old = matches[0] if matches else None
    record["id"] = old["id"] if old else "R-" + fingerprint([*anchor_key(record), position, ordinal])[:12]
    semantic_keys = ("requirement", "applies_to", "provision", "exact_quote")
    changed = old is not None and any(record[key] != old[key] for key in semantic_keys)
    record["requirement_revision"] = (old.get("requirement_revision", 1) + int(changed)) if old else 1
    history = list(old.get("requirement_history", [])) if old else []
    if changed:
        history.append({"revision": old.get("requirement_revision", 1),
                        **{key: old[key] for key in semantic_keys}})
    record["requirement_history"] = history
    # IDs may remain legacy; do not claim they were regenerated by the new scheme.
    record["identity_scheme"] = old.get("identity_scheme", "retained-legacy") if old else "legal-anchor-v1"
    return record
